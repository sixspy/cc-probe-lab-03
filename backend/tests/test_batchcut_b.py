"""失败测乙：批次摘要对账不得把半截影子批次当成整批成功（统计假绿）。

装载假绿（在栏残留）与统计假绿（批次对账）分属两服务，分轨核：
- 装载批次摘要必须带收口状态与失败指纹，失败批不得计入成功；
- 贯验对账须按批次分开现行在栏集合，影子批不冒充整批成功；
- 后续成功批不得被失败批污染。
"""
from app.services import 装载, 统计, 贯验, 收口, 目录


def _成批(前缀: str, n: int) -> dict:
    return {
        "批次编号": 前缀,
        "报文": [
            {
                "报文编号": f"{前缀}-{i}",
                "站点键": "站-北岭",
                "指标键": "PM25",
                "读数": 15.0 + i,
                "观测时": f"2026-11-25T09:{i:02d}:00Z",
            }
            for i in range(n)
        ],
    }


def _中断(monkeypatch, 在第几条后: int) -> None:
    计数 = {"i": 0}

    def 钩子(阶段, ev, 序号, 批次):
        if 阶段 == "报文落库后":
            计数["i"] += 1
            if 计数["i"] == 在第几条后:
                raise RuntimeError("模拟批中途炸")

    monkeypatch.setattr(装载, "装载故障点", 钩子)


def test_失败批不被摘要当成功(monkeypatch):
    _中断(monkeypatch, 2)
    失败报告 = 装载.装一批(_成批("乙-断", 4))
    失败批 = 失败报告["批次编号"]

    摘要 = 统计.装载批次摘要()
    行 = next(r for r in 摘要 if r["编号"] == 失败批)
    assert 行["收口"] == "失败清回"
    assert 行["失败指纹"]
    assert 行["入流"] == 0 or 行["收口"] != "整批成功"

    对账 = 统计.装载对账()
    assert 对账["成功批数"] == 0
    assert 对账["失败批数"] >= 1
    assert 失败批 in 对账["失败批次"]
    assert 失败批 not in 对账["成功批次"]
    # 影子前半截只在收口账，不进现行计数
    assert 对账["现行入流总数"] == 0


def test_失败后再来成功批_对账分轨不污染(monkeypatch):
    _中断(monkeypatch, 1)
    断批 = 装载.装一批(_成批("乙-断2", 3))["批次编号"]

    好报告 = 装载.装一批(_成批("乙-好", 2))
    好批 = 好报告["批次编号"]
    assert 好报告["收口"] == "整批成功"

    对账 = 统计.装载对账()
    assert 好批 in 对账["成功批次"]
    assert 断批 in 对账["失败批次"]
    assert 对账["成功批数"] == 1 and 对账["失败批数"] == 1
    assert 对账["现行入流总数"] == 2

    快照 = 贯验.只读快照()
    assert 好批 in 快照["批次在栏"]
    assert 快照["批次在栏"][好批] == 2
    assert 断批 not in 快照["批次在栏"]
    assert 断批 in 快照["失败收口批"]

    详 = 收口.批次收口查(好批)
    assert 详["收口"] == "整批成功"
    assert 详["现行在栏"] == 2
    assert 详["影子明细"] == []
    assert 目录.装载批次列表()  # 装载批次可见处仍列两批，但收口可分
