"""报文装载 → 入栏或坏点。

装载批事务收口编排（切流账册清回形态）：
- 批内主边（观测报文 / 入栏缓冲 / 坏点匣）同事务同成同败；
- 中途异常 → 整批回滚到批前，失败指纹与前半影子进只读收口账，正式表零残留；
- 全流程持收口.装载锁，二次补灌与收口并发不得交错半截双成。
"""
from __future__ import annotations
import json
import uuid
from app.db import 连接
from app.seed import 此刻
from app.services import 校验, 目录, 时间, 收口


def _批次号(体: dict) -> str:
    前 = str(体.get("批次编号") or "探批").strip() or "探批"
    return f"{前}-{uuid.uuid4().hex[:8]}"


def 装载故障点(阶段: str, ev: dict, 序号: int, 批次: str) -> None:
    """生产空操作；测试可 monkeypatch 注入中途故障。"""
    return None


def 装一批(体: dict) -> dict:
    批次 = _批次号(体 or {})
    报文 = (体 or {}).get("报文") or []
    报告 = {
        "批次编号": 批次, "入流": 0, "入栏": 0, "坏点": 0, "驳回": 0, "明细": [],
        "收口": 收口.整批成功, "失败指纹": "", "失败原因": "",
    }
    仓时 = 此刻()
    影子明细: list[dict] = []

    # 串行装载：补灌与任何收口/结栏共用一把锁，杜绝并发交错
    with 收口.装载锁:
        conn = 连接()
        try:
            # —— 批次预检失败：整批不写，直接走失败收口账 ——
            预检 = 校验.校验批次(体 or {})
            if 预检:
                原因 = "批次预检:" + 校验.摘要错误(预检)
                报告["收口"] = 收口.失败清回
                报告["失败原因"] = 原因
                报告["失败指纹"] = 收口.失败指纹(批次, 原因, [])
                报告["明细"].append({"命运": "批次预检", "说明": 校验.摘要错误(预检)})
                收口.记收口账(
                    conn, 批次, 仓时, 收口.失败清回, 原因,
                    报告["失败指纹"], {}, [],
                )
                conn.execute(
                    """INSERT INTO 装载批次(编号,时刻,入流,入栏,坏点,收口,失败指纹,报告)
                       VALUES (?,?,?,?,?,?,?,?)""",
                    (批次, 仓时, 0, 0, 0, 收口.失败清回, 报告["失败指纹"],
                     json.dumps(报告, ensure_ascii=False)),
                )
                conn.commit()
                return 报告

            规 = 目录.栏规()
            栏号 = 规.get("当前栏号", "B-demo")
            站集合 = {s["源键"] for s in 目录.站点列表()}

            try:
                for i, ev in enumerate(报文):
                    行错 = 校验.校验报文(ev)
                    if 行错:
                        报告["驳回"] += 1
                        报告["明细"].append({"命运": "驳回-校验", "说明": 校验.摘要错误(行错)})
                        continue
                    try:
                        时间.解析时(ev["观测时"])
                    except Exception:
                        报告["驳回"] += 1
                        报告["明细"].append({"命运": "驳回-观测时", "说明": ev.get("观测时")})
                        continue
                    编号 = ev["报文编号"]
                    if conn.execute("SELECT 1 FROM 观测报文 WHERE 报文编号=?", (编号,)).fetchone():
                        报告["驳回"] += 1
                        报告["明细"].append({"命运": "驳回-幂等", "说明": 编号})
                        continue
                    if ev["站点键"] not in 站集合:
                        报告["驳回"] += 1
                        报告["明细"].append({"命运": "驳回-未知站点", "说明": ev["站点键"]})
                        continue
                    读数 = float(ev["读数"])
                    漂 = 时间.漂移秒(ev["观测时"], 仓时)
                    conn.execute(
                        """INSERT INTO 观测报文(报文编号,站点键,指标键,读数,观测时,处理时,命运,批次编号)
                           VALUES (?,?,?,?,?,?,?,?)""",
                        (编号, ev["站点键"], ev["指标键"], 读数, ev["观测时"], 仓时, "已装载", 批次),
                    )
                    报告["入流"] += 1
                    ok, 原因 = 校验.过门槛(读数, 规, ev["指标键"])
                    if ok:
                        conn.execute(
                            """INSERT INTO 入栏缓冲(报文编号,站点键,指标键,读数,观测时,栏号,命运,入栏时,批次编号)
                               VALUES (?,?,?,?,?,?,?,?,?)""",
                            (编号, ev["站点键"], ev["指标键"], 读数, ev["观测时"], 栏号, "在栏", 仓时, 批次),
                        )
                        conn.execute("UPDATE 观测报文 SET 命运=? WHERE 报文编号=?", ("已入栏", 编号))
                        报告["入栏"] += 1
                        报告["明细"].append({
                            "命运": "入栏",
                            "报文编号": 编号,
                            "栏号": 栏号,
                            "漂移秒": 漂,
                            "受控": 校验.指标是否受控(ev["指标键"]),
                        })
                    else:
                        conn.execute(
                            """INSERT INTO 坏点匣(报文编号,站点键,原因,读数,观测时,入匣时,批次编号)
                               VALUES (?,?,?,?,?,?,?)""",
                            (编号, ev["站点键"], 原因, 读数, ev["观测时"], 仓时, 批次),
                        )
                        conn.execute("UPDATE 观测报文 SET 命运=? WHERE 报文编号=?", ("已坏点", 编号))
                        报告["坏点"] += 1
                        报告["明细"].append({"命运": "坏点", "报文编号": 编号, "原因": 原因})

                    # 先留影子，再走故障点：钩抛错时前半已完整入账
                    影子明细.append({
                        "报文编号": 编号,
                        "站点键": ev["站点键"],
                        "指标键": ev["指标键"],
                        "读数": 读数,
                        "观测时": ev["观测时"],
                        "命运": "已入栏" if ok else "已坏点",
                    })
                    # 一条主边落库后的故障注入点（测试模拟写入中断）
                    装载故障点("报文落库后", ev, i, 批次)

                # —— 整批成功：主边与批次/收口账同事务提交 ——
                收口.记收口账(
                    conn, 批次, 仓时, 收口.整批成功, "", "",
                    {"入流": 报告["入流"], "入栏": 报告["入栏"], "坏点": 报告["坏点"]},
                    [],
                )
                conn.execute(
                    """INSERT INTO 装载批次(编号,时刻,入流,入栏,坏点,收口,失败指纹,报告)
                       VALUES (?,?,?,?,?,?,?,?)""",
                    (批次, 仓时, 报告["入流"], 报告["入栏"], 报告["坏点"],
                     收口.整批成功, "", json.dumps(报告, ensure_ascii=False)),
                )
                conn.commit()
                return 报告
            except Exception as 异常:
                # —— 中途失败：主边整批清回批前，另起干净事务只钉收口账 ——
                conn.rollback()
                原因 = f"{type(异常).__name__}: {异常}"
                指纹 = 收口.失败指纹(批次, 原因, 影子明细)
                报告["收口"] = 收口.失败清回
                报告["失败原因"] = 原因
                报告["失败指纹"] = 指纹
                报告["明细"].append({"命运": "收口-失败清回", "说明": 原因, "失败指纹": 指纹})
                收口.记收口账(
                    conn, 批次, 仓时, 收口.失败清回, 原因, 指纹,
                    {"入流": 报告["入流"], "入栏": 报告["入栏"], "坏点": 报告["坏点"]},
                    影子明细,
                )
                conn.execute(
                    """INSERT INTO 装载批次(编号,时刻,入流,入栏,坏点,收口,失败指纹,报告)
                       VALUES (?,?,?,?,?,?,?,?)""",
                    (批次, 仓时, 0, 0, 0, 收口.失败清回, 指纹,
                     json.dumps(报告, ensure_ascii=False)),
                )
                conn.commit()
                return 报告
        finally:
            conn.close()
